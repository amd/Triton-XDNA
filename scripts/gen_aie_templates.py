"""Write amd_triton_npu/backend/aie_templates/ops.mlir: the IR Peano's
clang -O2 emits for ops.cc, the lowering of tl.extra.air.aie's template
ops. With --check, compare instead (exit 1 if they differ).

The aie2p intrinsics are renamed (__aie2p__.) for the import and named
back after it: the importer takes a function named llvm.* for an intrinsic
of the LLVM it is built with, which has no aie2p ones.

    python3 scripts/gen_aie_templates.py [--check]

Needs Peano (PEANO_INSTALL_DIR or the llvm-aie package) and aie_api's
headers (the mlir_aie package), and air-translate on PATH.
"""

import glob
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.join(HERE, "..", "amd_triton_npu", "backend", "aie_templates")
SRC, OUT = os.path.join(DIR, "ops.cc"), os.path.join(DIR, "ops.mlir")
_HIDDEN = "__aie2p__."


def _find(paths, rel):
    for d in paths:
        if d and os.path.exists(os.path.join(d, rel)):
            return os.path.abspath(d)
    return None


def peano():
    site = glob.glob(os.path.join(sys.prefix, "lib", "python3*", "site-packages"))
    return _find(
        [os.environ.get("PEANO_INSTALL_DIR", "")]
        + [os.path.join(s, "llvm-aie") for s in site],
        "bin/clang++",
    )


def aie_include():
    site = glob.glob(os.path.join(sys.prefix, "lib", "python3*", "site-packages"))
    dirs = [os.path.join(s, "mlir_aie", "include") for s in site]
    if os.environ.get("MLIR_AIE_INSTALL_DIR"):
        dirs.insert(0, os.path.join(os.environ["MLIR_AIE_INSTALL_DIR"], "include"))
    return _find(dirs, "aie_api/aie.hpp")


def generate():
    """ops.mlir's text, made from ops.cc now."""
    p, inc = peano(), aie_include()
    if p is None or inc is None:
        raise RuntimeError("needs Peano and aie_api's headers")
    with tempfile.TemporaryDirectory() as d:
        ll, llr, mlir = (os.path.join(d, n) for n in ("ops.ll", "ops.r.ll", "ops.mlir"))
        subprocess.run(
            [
                os.path.join(p, "bin", "clang++"),
                "-O2",
                "-std=c++20",
                "--target=aie2p-none-unknown-elf",
                "-DNDEBUG",
                "-Wno-parentheses",
                "-Wno-attributes",
                "-Wno-macro-redefined",
                "-Wno-empty-body",
                "-Wno-deprecated-declarations",
                f"-I{inc}",
                "-D__AIE_API_AIE_ADF_HPP__",
                "-S",
                "-emit-llvm",
                SRC,
                "-o",
                ll,
            ],
            check=True,
        )
        text = open(ll).read().replace("@llvm.aie2p.", "@" + _HIDDEN)
        # (attributes and metadata, which the importer may not know)
        text = "\n".join(
            ln for ln in text.splitlines() if not ln.startswith(("attributes", "!"))
        )
        text = re.sub(r" #\d+", "", text)
        text = re.sub(r", !(tbaa|noalias|alias\.scope|llvm\.loop) !\d+", "", text)
        open(llr, "w").write(text)
        subprocess.run(["air-translate", "--import-llvm", llr, "-o", mlir], check=True)
        out = open(mlir).read().replace("@" + _HIDDEN, "@llvm.aie2p.")
    head = (
        "// Generated by scripts/gen_aie_templates.py from ops.cc (Peano clang -O2):\n"
        "// do not edit.\n"
    )
    return head + out


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("ops.mlir is up to date" if same else "ops.mlir differs from ops.cc's IR")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
